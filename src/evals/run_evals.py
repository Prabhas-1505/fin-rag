# Note: In a real project, you would `pip install ragas datasets`
# This script sets up the automated evaluation pipeline to run against a Golden Test Dataset.

import json
from typing import List, Dict, cast
import os
from dotenv import load_dotenv

# Load env variables for OpenAI API credentials
load_dotenv()

# Mocking Ragas imports for structural demonstration
try:
    from datasets import Dataset
    from ragas import evaluate
    from ragas.metrics import faithfulness, context_recall
    from ragas.evaluation import EvaluationResult
except ImportError:
    print("Warning: 'ragas' or 'datasets' not installed. Please run `pip install ragas datasets`.")
    evaluate = None
    EvaluationResult = None

def load_golden_dataset(path: str = "golden_dataset.json") -> List[Dict]:
    """
    Loads the golden dataset consisting of questions, ground truth answers, and context.
    """
    if not os.path.exists(path):
        print(f"Golden dataset not found at {path}. Returning dummy data.")
        return [
            {
                "question": "What was Apple's Q4 revenue?",
                "ground_truth": "Apple's Q4 revenue was $89.5 billion.",
                "contexts": ["Apple reported Q4 revenue of $89.5 billion, down 1% year over year."],
                "answer": "Apple's Q4 revenue was $89.5 billion." # Generated by your system
            }
        ]
        
    with open(path, "r") as f:
        return json.load(f)

def run_evaluation(data: List[Dict]):
    """
    Runs the Ragas evaluation for Faithfulness and Context Recall.
    """
    if not evaluate:
        print("Cannot run evaluation without ragas library.")
        return
        
    # Format for Ragas dataset
    dataset = Dataset.from_list(data)
    
    print("Starting evaluation pipeline...")
    
    # Run evaluation
    result_raw = evaluate(
        dataset,
        metrics=[
            faithfulness,
            context_recall
        ]
    )
    
    if EvaluationResult is None:
        print("EvaluationResult class not available.")
        return
        
    result = cast(EvaluationResult, result_raw)
    
    print("Evaluation Results:")
    print(result)
    
    # Extract lists of scores and calculate their mean
    faithfulness_scores = result["faithfulness"]
    context_recall_scores = result["context_recall"]
    
    faithfulness_mean = sum(faithfulness_scores) / len(faithfulness_scores) if faithfulness_scores else 0.0
    context_recall_mean = sum(context_recall_scores) / len(context_recall_scores) if context_recall_scores else 0.0
    
    # CI/CD check logic
    if faithfulness_mean < 0.90:
        print(f"CI/CD Pipeline Failed: Faithfulness {faithfulness_mean:.4f} below 90% threshold.")
        exit(1)
        
    if context_recall_mean < 0.85:
        print(f"CI/CD Pipeline Failed: Context Recall {context_recall_mean:.4f} below 85% threshold.")
        exit(1)
        
    print("CI/CD Pipeline Passed: All metrics are within acceptable thresholds.")

if __name__ == "__main__":
    data = load_golden_dataset()
    run_evaluation(data)
